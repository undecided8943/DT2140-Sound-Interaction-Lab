let lastAngle = null;
let lastCheckTime = 0;

function rotationChange(rotx, roty, rotz) {
    const threshold = 10;
    
    if (millis() - lastCheckTime < 1000) {
        return;
    }
    lastCheckTime = millis();

    if (lastAngle == null) {
        lastAngle = rotz;
        return;
    }

    const angle = rotz;

    const change = Math.abs(((rotz - lastAngle + 540) % 360) - 180);
    if (change > threshold) {
        playAudio();
    }
    lastAngle = angle;
}

