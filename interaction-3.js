function playAudio() {
    if (!dspNode) {
        return;
    }
    if (audioContext.state === 'suspended') {
        return;
    }
    const [minPos, maxPos] = getMinMaxParam("/door/door/position");
    const [minVol, maxVol] = getMinMaxParam("/door/volume");

    dspNode.setParamValue("/door/volume", maxVol)
    dspNode.setParamValue("/door/door/position", maxPos)
    setTimeout(() => { dspNode.setParamValue("/door/door/position", minPos) }, 800);
}

